function bulletList(items: string[]): string {
  return items.map((item) => `- ${item}`).join("\n");
}

export function buildSystemPrompt(mode: ModeId): string {
  const label = getMode(mode).label;
  const scope = MODE_SCOPES[mode];

  return `${BASE_PROMPT}

# Текущий режим: «${label}»
Задача режима — ${scope.task}.

Подходит:
${bulletList(scope.fits)}

Не подходит:
${bulletList(scope.misfits)}

Как отвечать в этом режиме:
${MODE_INSTRUCTIONS[mode]}

Перед ответом проверь: подходит ли запрос под режим «${label}»? Если явно нет — ответь по шаблону несоответствия, первая строка дословно: **Запрос не подходит под режим «${label}».**`;
}

function summaryWordBudget(text: string): number {
  const words = text.split(/\s+/).filter(Boolean).length;
  return Math.min(250, Math.max(40, Math.round(words * 0.25)));
}

export function buildUserMessage(mode: ModeId, question: string): string {
  if (mode !== "summarize") return question;
  return `Сожми текст ниже. Бюджет: не больше ${summaryWordBudget(question)} слов.\n\n<text>\n${question}\n</text>`;
}
